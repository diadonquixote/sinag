export const MESSAGES: Record<Lang, Record<MessageKey, string>> = { en, fil };

/** Fills {placeholders}. Missing values are left visible rather than silently blank. */
export function format(template: string, vars?: Record<string, string | number>): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (whole, name: string) => (name in vars ? String(vars[name]) : whole));
}

export function translate(lang: Lang, key: MessageKey, vars?: Record<string, string | number>): string {
  return format(MESSAGES[lang][key] ?? MESSAGES.en[key], vars);
}

/** Reads a language from a cookie value or an Accept-Language header. English unless Filipino or Tagalog comes first. */
export function pickLang(cookie: string | undefined, acceptLanguage: string | null | undefined): Lang {
  if (cookie === "en" || cookie === "fil") return cookie;
  const firstChoice = (acceptLanguage ?? "").split(",")[0]?.trim().toLowerCase() ?? "";
  return firstChoice.startsWith("fil") || firstChoice.startsWith("tl") ? "fil" : "en";
}
